test('conta, categoria e lançamento persistem; pagar, desfazer, editar e excluir funcionam pela interface', async ({ page }) => {
  const sessao = await cadastrar(page)
  const sufixo = randomUUID().slice(0, 8)
  const contaNome = `Cartão fictício ${sufixo}`
  const conta = await criarConta(page, contaNome, true)
  await page.goto('/categorias')
  await page.getByRole('button', { name: 'Adicionar categoria', exact: true }).click()
  const categoriaJanela = page.getByRole('dialog', { name: 'Adicionar categoria', exact: true })
  const categoriaNome = `Categoria fictícia ${sufixo}`
  await categoriaJanela.getByLabel('Nome', { exact: true }).fill(categoriaNome)
  const categoria = await salvar(page, categoriaJanela, '/api/categories')
  await page.goto('/lancamentos')
  await page.getByRole('button', { name: '+ Novo lançamento', exact: true }).click()
  const janela = page.getByRole('dialog', { name: 'Novo lançamento', exact: true })
  const titulo = `Despesa fictícia ${sufixo}`
  await janela.getByLabel('Descrição', { exact: true }).fill(titulo)
  await janela.getByLabel('Valor (R$)', { exact: true }).fill('12.34')
  await janela.getByLabel('Vencimento / recebimento', { exact: true }).fill(hoje())
  await selecionar(page, janela, 'Conta', contaNome)
  await selecionar(page, janela, 'Categoria', categoriaNome)
  const criacao = page.waitForResponse(resposta => new URL(resposta.url()).pathname === '/api/entries/repeat' && resposta.request().method() === 'POST')
  await janela.getByRole('button', { name: 'Salvar lançamento', exact: true }).click()
  expect((await criacao).status()).toBe(201)
  await expect(janela).toBeHidden()
  const bootstrap = await (await page.request.get('/api/bootstrap', { headers: autorizacao(sessao) })).json()
  const registro = (bootstrap.entries as { id: string; title: string; accountId: string; categoryId: string; amount: number }[]).find(item => item.title === titulo)
  expect(registro).toMatchObject({ accountId: conta.id, categoryId: categoria.id, amount: 12.34 })
  expect(registro).toBeDefined()
  const id = registro!.id
  let linha = page.getByRole('row').filter({ hasText: titulo })
  await expect(linha).toBeVisible()
  await linha.getByRole('button', { name: 'Pagar', exact: true }).click()
  await expect(linha.getByRole('button', { name: 'Desfazer', exact: true })).toBeVisible()
  expect((await (await page.request.get(`/api/entries/${id}`, { headers: autorizacao(sessao) })).json()).status).toBe('paid')
  await linha.getByRole('button', { name: 'Desfazer', exact: true }).click()
  await expect(linha.getByRole('button', { name: 'Pagar', exact: true })).toBeVisible()
  await linha.getByRole('button', { name: `Editar ${titulo}`, exact: true }).click()
  const edicao = page.getByRole('dialog', { name: 'Editar lançamento', exact: true })
  const novoTitulo = `Despesa ajustada ${sufixo}`
  await edicao.getByLabel('Descrição', { exact: true }).fill(novoTitulo)
  await edicao.getByLabel('Valor (R$)', { exact: true }).fill('56.78')
  await salvar(page, edicao, `/api/entries/${id}`, 'PUT', 'Salvar lançamento')
  const persistido = await (await page.request.get(`/api/entries/${id}`, { headers: autorizacao(sessao) })).json()
  expect(persistido).toMatchObject({ title: novoTitulo, amount: 56.78, status: 'pending' })
  linha = page.getByRole('row').filter({ hasText: novoTitulo })
  await linha.getByRole('button', { name: `Excluir ${novoTitulo}`, exact: true }).click()
  await page.getByRole('dialog', { name: 'Excluir lançamento?', exact: true }).getByRole('button', { name: 'Excluir', exact: true }).click()
  await expect(linha).toHaveCount(0)
  expect((await page.request.get(`/api/entries/${id}`, { headers: autorizacao(sessao) })).status()).toBe(404)
})

test('recorrência gera dois meses sem duplicar e sua exclusão remove somente os futuros não pagos', async ({ page }) => {
  const sessao = await cadastrar(page)
  await page.goto('/recorrencias')
  await page.getByRole('button', { name: 'Adicionar recorrência', exact: true }).click()
  const janela = page.getByRole('dialog', { name: 'Adicionar recorrência', exact: true })
  const titulo = `Assinatura fictícia ${randomUUID().slice(0, 8)}`
  await janela.getByLabel('Nome', { exact: true }).fill(titulo)
  await janela.getByLabel('Valor (R$)', { exact: true }).fill('19,90')
  await janela.getByLabel('Dia do vencimento', { exact: true }).fill('31')
  const regra = await salvar(page, janela, '/api/rules')
  for (let repeticao = 0; repeticao < 2; repeticao++) {
    await page.getByRole('button', { name: 'Atualizar lançamentos recorrentes', exact: true }).click()
    const geracao = page.getByRole('dialog', { name: 'Atualizar lançamentos recorrentes', exact: true })
    await geracao.getByLabel('Quantidade de meses', { exact: true }).fill('2')
    const resposta = page.waitForResponse(resposta => new URL(resposta.url()).pathname === '/api/rules/rebuild' && resposta.request().method() === 'POST')
    await geracao.getByRole('button', { name: 'Atualizar lançamentos recorrentes', exact: true }).click()
    expect((await resposta).status()).toBe(200)
    await expect(geracao).toBeHidden()
  }
  const entradas = (await (await page.request.get('/api/entries', { headers: autorizacao(sessao) })).json()).entries as { ruleId: string; amount: number }[]
  expect(entradas.filter(item => item.ruleId === regra.id)).toHaveLength(2)
  expect(entradas.every(item => item.amount === 19.9)).toBe(true)
  await page.getByRole('row').filter({ hasText: titulo }).getByRole('button', { name: `Excluir ${titulo}`, exact: true }).click()
  await page.getByRole('dialog', { name: 'Excluir recorrência', exact: true }).getByRole('button', { name: 'Excluir', exact: true }).click()
  await expect(page.getByRole('row').filter({ hasText: titulo })).toHaveCount(0)
  expect((await page.request.get(`/api/rules/${regra.id}`, { headers: autorizacao(sessao) })).status()).toBe(404)
  expect((await (await page.request.get('/api/entries', { headers: autorizacao(sessao) })).json()).entries).toHaveLength(0)
})

test('desejo guarda links sem carregá-los, filtra prioridade e situação, edita e exclui', async ({ page }) => {
  const sessao = await cadastrar(page)
  const acessosExternos: string[] = []
  page.on('request', requisicao => { if (new URL(requisicao.url()).hostname === 'example.invalid') acessosExternos.push(requisicao.url()) })
  await page.goto('/desejos')
  await page.getByRole('button', { name: 'Adicionar desejo', exact: true }).click()
  const janela = page.getByRole('dialog', { name: 'Adicionar desejo', exact: true })
  const nome = `Plano fictício ${randomUUID().slice(0, 8)}`
  await janela.getByLabel('Nome', { exact: true }).fill(nome)
  await janela.getByLabel('Valor (R$)', { exact: true }).fill('123,45')
  await selecionar(page, janela, 'Prioridade', 'Alta')
  await janela.getByLabel('Link do produto (opcional)', { exact: true }).fill('https://example.invalid/produto-ficticio')
  await janela.getByLabel('Link da imagem (opcional)', { exact: true }).fill('https://example.invalid/imagem.png')
  const desejo = await salvar(page, janela, '/api/wishlist')
  await selecionar(page, page, 'Prioridade', 'Alta')
  await selecionar(page, page, 'Situação', 'Quero comprar')
  const linha = page.getByRole('row').filter({ hasText: nome })
  await expect(linha).toBeVisible()
  await linha.getByRole('button', { name: `Editar ${nome}`, exact: true }).click()
  const edicao = page.getByRole('dialog', { name: 'Editar desejo', exact: true })
  await selecionar(page, edicao, 'Situação', 'Já comprei')
  await salvar(page, edicao, `/api/wishlist/${desejo.id}`, 'PUT')
  await expect(linha).toHaveCount(0)
  await selecionar(page, page, 'Situação', 'Todas as situações')
  await expect(linha).toBeVisible()
  await expect(linha).toContainText('Já comprei')
  const persistido = await (await page.request.get(`/api/wishlist/${desejo.id}`, { headers: autorizacao(sessao) })).json()
  expect(persistido).toMatchObject({ price: 123.45, priority: 'high', status: 'bought' })
  await linha.getByRole('button', { name: `Excluir ${nome}`, exact: true }).click()
  await page.getByRole('dialog', { name: 'Excluir desejo', exact: true }).getByRole('button', { name: 'Excluir', exact: true }).click()
  await expect(linha).toHaveCount(0)
  expect((await page.request.get(`/api/wishlist/${desejo.id}`, { headers: autorizacao(sessao) })).status()).toBe(404)
  expect(acessosExternos).toEqual([])
})

test('duas sessões mantêm famílias isoladas no navegador e na API', async ({ page, browser, falhas }) => {
  const sessaoA = await cadastrar(page)
  const nomeA = `Conta família A ${randomUUID().slice(0, 8)}`
  const contaA = await criarConta(page, nomeA)
  const segundoContexto = await browser.newContext({ baseURL: 'http://127.0.0.1:5173', viewport: { width: 1440, height: 960 },
    locale: 'pt-BR', timezoneId: 'America/Sao_Paulo', reducedMotion: 'reduce' })
  try {
    const segundaPagina = await segundoContexto.newPage()
    observar(segundaPagina, falhas)
    const sessaoB = await cadastrar(segundaPagina)
    const nomeB = `Conta família B ${randomUUID().slice(0, 8)}`
    const contaB = await criarConta(segundaPagina, nomeB)
    await expect(segundaPagina.getByRole('row').filter({ hasText: nomeA })).toHaveCount(0)
    await page.reload()
    await expect(page.getByRole('row').filter({ hasText: nomeA })).toBeVisible()
    await expect(page.getByRole('row').filter({ hasText: nomeB })).toHaveCount(0)
    expect((await segundaPagina.request.get(`/api/accounts/${contaA.id}`, { headers: autorizacao(sessaoB) })).status()).toBe(404)
    expect((await page.request.get(`/api/accounts/${contaB.id}`, { headers: autorizacao(sessaoA) })).status()).toBe(404)
    await page.getByRole('button', { name: 'Sair', exact: true }).click()
    await expect(page).toHaveURL(/\/login$/)
    expect((await page.request.get('/api/bootstrap', { headers: autorizacao(sessaoA) })).status()).toBe(401)
    await segundaPagina.reload()
    await expect(segundaPagina.getByRole('row').filter({ hasText: nomeB })).toBeVisible()
  } finally { await segundoContexto.close() }
})

test('os filtros de conta e período dos dois gráficos mantêm estado independente', async ({ page }) => {
  const sessao = await cadastrar(page)
  const contaA = await prepararConta(page, sessao, 'Conta fictícia A')
  const contaB = await prepararConta(page, sessao, 'Conta fictícia B')
  await prepararLancamento(page, sessao, { title: 'Despesa fictícia A', amount: 10, accountId: contaA.id })
  await prepararLancamento(page, sessao, { title: 'Despesa fictícia B', amount: 20, accountId: contaB.id })
  await page.reload()
  const fluxo = page.locator('.ff-panel').filter({ has: page.getByRole('heading', { name: 'Fluxo de caixa', exact: true }) })
  const categorias = page.locator('.ff-panel').filter({ has: page.getByRole('heading', { name: 'Para onde vai seu dinheiro', exact: true }) })
  await expect(fluxo.getByText(/30,00/)).toBeVisible()
  await expect(categorias.getByText(/30,00/)).toBeVisible()
  await selecionar(page, fluxo, 'Conta: Fluxo de caixa', 'Conta fictícia A')
  await expect(fluxo.getByText(/10,00/)).toBeVisible()
  await expect(categorias.getByText(/30,00/)).toBeVisible()
  await selecionar(page, categorias, 'Conta: Para onde vai seu dinheiro', 'Conta fictícia B')
  await expect(categorias.getByText(/20,00/)).toBeVisible()
  await expect(fluxo.getByText(/10,00/)).toBeVisible()
  const periodoOriginal = await categorias.getByLabel('Período: Para onde vai seu dinheiro', { exact: true }).inputValue()
  const anterior = new Date(`${periodoOriginal}-01T12:00:00Z`)
  anterior.setUTCMonth(anterior.getUTCMonth() - 1)
  await fluxo.getByLabel('Período: Fluxo de caixa', { exact: true }).fill(anterior.toISOString().slice(0, 7))
  await expect(fluxo.getByText('Sem movimentação neste período', { exact: true })).toBeVisible()
  await expect(categorias.getByLabel('Período: Para onde vai seu dinheiro', { exact: true })).toHaveValue(periodoOriginal)
  await expect(categorias.getByText(/20,00/)).toBeVisible()
})

for (const largura of [320, 768, 1440]) for (const tema of ['light', 'dark'] as const) {
  test(`layout ${largura}px no tema ${tema} mantém conteúdo utilizável`, async ({ page }, informacoes) => {
    await page.setViewportSize({ width: largura, height: 960 })
    await page.emulateMedia({ colorScheme: tema })
    const sessao = await cadastrar(page)
    const bootstrap = await (await page.request.get('/api/bootstrap', { headers: autorizacao(sessao) })).json()
    expect((await page.request.post('/api/settings/theme', { headers: autorizacao(sessao), data: {
      themeMode: tema, densityMode: 'comfortable', colorTokens: bootstrap.settings.colorTokens
    } })).status()).toBe(200)
    const conta = await prepararConta(page, sessao, 'Conta visual fictícia')
    await prepararLancamento(page, sessao, { title: 'Receita visual fictícia', amount: 1250, kind: 'income', accountId: conta.id, status: 'paid' })
    await prepararLancamento(page, sessao, { title: 'Despesa visual fictícia', amount: 350.25, accountId: conta.id })
    for (const [rota, nome] of [['/', 'panorama'], ['/contas', 'contas'], ['/lancamentos', 'lancamentos']] as const) {
      await page.goto(rota)
      await expect(page.locator('html')).toHaveAttribute('data-theme', tema)
      await expect(page.locator('#conteudo')).toBeVisible()
      if (rota === '/') await expect(page.getByRole('heading', { name: 'Um olhar para o seu mês.', exact: true })).toBeVisible()
      else await expect(page.getByRole('row').filter({ hasText: rota === '/contas' ? 'Conta visual fictícia' : 'Despesa visual fictícia' })).toBeVisible()
      await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
      const captura = informacoes.outputPath(`${nome}-${largura}-${tema}.png`)
      await page.screenshot({ path: captura, fullPage: true })
      await informacoes.attach(`${nome}-${largura}-${tema}`, { path: captura, contentType: 'image/png' })
    }
    await page.goto('/contas')
    await page.getByRole('button', { name: 'Adicionar conta', exact: true }).click()
    const janela = page.getByRole('dialog', { name: 'Adicionar conta', exact: true })
    await selecionar(page, janela, 'Tipo de conta', 'Cartão de crédito')
    await expect(janela.getByLabel('Limite do cartão (R$)', { exact: true })).toBeVisible()
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    const captura = informacoes.outputPath(`formulario-cartao-${largura}-${tema}.png`)
    await page.screenshot({ path: captura, fullPage: true })
    await informacoes.attach(`formulario-cartao-${largura}-${tema}`, { path: captura, contentType: 'image/png' })
  })
}
